def _percentile_to_buckets(values):
    """Convert 20 percentile values to discrete distribution buckets (prob, midpoint)."""
    buckets = []
    for i in range(len(PCTS)):
        prob = PCTS[i] - (PCTS[i-1] if i > 0 else 0.0)
        v    = (values[i] + (values[i-1] if i > 0 else values[0])) / 2.0
        buckets.append((prob, v))
    return buckets


